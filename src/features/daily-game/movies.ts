export interface GameMovie {
  id: string;
  title: string;
  year: number;
  directors: readonly string[];
  cast: readonly string[];
  genres: readonly string[];
  themes: readonly string[];
  series?: string;
}

const slug = (value: string): string =>
  value
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const movie = (
  title: string,
  year: number,
  directors: string[],
  cast: string[],
  genres: string[],
  themes: string[],
  series?: string,
): GameMovie => ({
  id: `${slug(title)}-${year}`,
  title,
  year,
  directors,
  cast,
  genres,
  themes,
  series,
});

